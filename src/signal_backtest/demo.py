"""SYNTHETIC demo data - only to show the backtest report format.

Every account id ends in ``.demo-synthetic`` and the outcomes file starts with a ``# SYNTHETIC``
comment line, so demo data can never be mistaken for (or mixed into) real outcomes.
Planted effects (so the report has something to find): hiring_web 2x, recent_funding 1.8x,
github_active 0.6x; every other signal has no effect and should come out as noise.
"""

from __future__ import annotations

import json
import random
from datetime import UTC, datetime, timedelta
from pathlib import Path

from .store import Company, Observation

DEMO_SUFFIX = ".demo-synthetic"
PLANTED = {"hiring_web": 2.0, "recent_funding": 1.8, "github_active": 0.6}


def generate(
    n: int = 3000, base_rate: float = 0.04, seed: int = 42
) -> tuple[list[Company], list[Observation], list[dict[str, str]]]:
    rng = random.Random(seed)
    t0 = datetime(2026, 11, 20, 6, 0, tzinfo=UTC)
    t1 = t0 + timedelta(days=7)
    companies: list[Company] = []
    obs: list[Observation] = []
    outcomes: list[dict[str, str]] = []
    for i in range(n):
        aid = f"acct{i:04d}{DEMO_SUFFIX}"
        seg = "agency" if rng.random() < 0.3 else "b2b_saas"
        companies.append(
            Company(
                aid,
                f"Demo {i}",
                f"https://{aid}/",
                "US",
                seg,
                "synthetic",
                rng.choice([8, 25, 60, 150, 400]),
            )
        )
        web = rng.random() < 0.25
        mkt = rng.random() < 0.3
        legacy = rng.random() < 0.15
        wp = rng.random() < 0.3
        gh = rng.random() < 0.3
        funded = rng.random() < 0.1
        for ts in (t0, t1):
            iso = ts.isoformat().replace("+00:00", "Z")
            total = float(web + mkt + rng.randint(0, 3))
            for kind, v in (
                ("total", total),
                ("web", float(web)),
                ("marketing", float(mkt)),
                ("design", 0.0),
            ):
                obs.append(
                    Observation(
                        aid,
                        "jobs",
                        f"open_roles_{kind}",
                        "greenhouse",
                        "",
                        v,
                        json.dumps({"method": "link"}),
                        iso,
                    )
                )
            obs.append(Observation(aid, "techstack", "tech_scan", "", "ok", 1.0, "", iso))
            if legacy:
                obs.append(
                    Observation(aid, "techstack", "tech_group", "legacy_builder", "", 1.0, "", iso)
                )
            if wp:
                obs.append(
                    Observation(aid, "techstack", "tech_group", "wordpress", "", 1.0, "", iso)
                )
            obs.append(
                Observation(
                    aid,
                    "website",
                    "structure_hash",
                    "",
                    "a" if ts == t0 or rng.random() < 0.9 else "b",
                    None,
                    "",
                    iso,
                )
            )
            if gh:
                obs.append(Observation(aid, "github", "repos_pushed_30d", "org", "", 3.0, "", iso))
        if funded:
            obs.append(
                Observation(
                    aid,
                    "funding",
                    "funding_news",
                    f"https://news/{i}",
                    f"Demo {i} raises seed",
                    None,
                    "",
                    (t1 - timedelta(days=3)).isoformat().replace("+00:00", "Z"),
                )
            )
        p = base_rate
        p *= PLANTED["hiring_web"] if web else 1.0
        p *= PLANTED["recent_funding"] if funded else 1.0
        p *= PLANTED["github_active"] if gh else 1.0
        replied = rng.random() < p
        positive = replied and rng.random() < 0.4
        meeting = positive and rng.random() < 0.5
        sent = t1 + timedelta(days=1 + rng.randint(0, 20), hours=rng.randint(0, 23))
        outcomes.append(
            {
                "account_id": aid,
                "sent_at": sent.isoformat().replace("+00:00", "Z"),
                "replied": str(int(replied)),
                "positive": str(int(positive)),
                "meeting": str(int(meeting)),
            }
        )
    return companies, obs, outcomes


def write_outcomes(path: Path, rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    cols = ["account_id", "sent_at", "replied", "positive", "meeting"]
    with path.open("w") as fh:
        fh.write("# SYNTHETIC DEMO OUTCOMES - generated by `signal-backtest demo`; not real data\n")
        fh.write(",".join(cols) + "\n")
        for r in rows:
            fh.write(",".join(r[c] for c in cols) + "\n")
